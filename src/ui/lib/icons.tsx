export function CategoryIcon({
  name,
  size = 16,
  className,
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const I = ICONS[name] ?? Tag;
  return <I size={size} className={className} aria-hidden="true" strokeWidth={1.9} />;
}
